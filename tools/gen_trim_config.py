"""Write a config fragment that turns off every module (=m) not on the allowlist.

Usage: gen_trim_config.py BASE_CONFIG KEEP_FILE [--keep-from FILE ...] > trim.config

BASE_CONFIG  the .config to trim (only its =m options are considered)
KEEP_FILE    patterns, one per line: shell-style globs on symbol names (no CONFIG_),
             '!PATTERN' to exclude; '#' starts a comment
--keep-from  extra files of symbols to keep: one bare symbol per line, or config-fragment lines
             (CONFIG_X=..., '# CONFIG_X is not set') whose symbol is kept as written

The fragment it prints lists one '# CONFIG_X is not set' per dropped module. A summary goes to
stderr. Read-only; Python stdlib only.
"""
import argparse
import fnmatch
import re
import sys


def patterns(path):
    inc, exc = [], []
    for line in open(path):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        (exc if line.startswith('!') else inc).append(line.lstrip('!'))
    return inc, exc


def symbols(path):
    out = set()
    for line in open(path):
        m = re.match(r'\s*(?:# )?CONFIG_(\w+)(?:=| is not set)', line)
        if m:
            out.add(m.group(1))
            continue
        line = line.split('#', 1)[0].strip()
        if re.fullmatch(r'\w+', line or '-'):
            out.add(line)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('base')
    ap.add_argument('keep')
    ap.add_argument('--keep-from', action='append', default=[])
    a = ap.parse_args()

    inc, exc = patterns(a.keep)
    extra = set()
    for f in a.keep_from:
        extra |= symbols(f)
    mods = [m.group(1) for m in (re.match(r'CONFIG_(\w+)=m$', l.strip()) for l in open(a.base)) if m]

    kept, dropped = [], []
    for s in mods:
        hit = s in extra or (any(fnmatch.fnmatchcase(s, p) for p in inc) and
                             not any(fnmatch.fnmatchcase(s, p) for p in exc))
        (kept if hit else dropped).append(s)

    print('# Generated by tools/gen_trim_config.py: modules not on the allowlist. Do not edit.')
    for s in sorted(dropped):
        print(f'# CONFIG_{s} is not set')
    print(f'{len(mods)} modules in base: {len(kept)} kept, {len(dropped)} turned off',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
